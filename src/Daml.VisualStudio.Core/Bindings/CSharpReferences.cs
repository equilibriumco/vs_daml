using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Daml.VisualStudio.Core.Bindings;

/// <summary>A use, in C#, of the C# that stands for a Daml declaration.</summary>
/// <param name="Project">The project that compiles it; several, comma-separated, once summarized.</param>
/// <param name="FilePath">The file.</param>
/// <param name="Line">The line, from one.</param>
/// <param name="Column">The column, from one.</param>
/// <param name="Start">Where the name starts in the file.</param>
/// <param name="Length">How long the name is.</param>
/// <param name="Code">The line's code, trimmed.</param>
public sealed record CSharpReference(string Project, string FilePath, int Line, int Column, int Start, int Length, string Code);

/// <summary>What the C# references of a Daml declaration come to.</summary>
public static class CSharpReferences
{
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    /// <summary>
    /// Each place in the source once, however many projects or target frameworks compile it (a
    /// linked file, a project with several frameworks), with every project named; in file and line order.
    /// </summary>
    public static IReadOnlyList<CSharpReference> Summarize(IEnumerable<CSharpReference> references) =>
        (references ?? throw new ArgumentNullException(nameof(references)))
            .GroupBy(r => (File: r.FilePath.ToUpperInvariant(), r.Start, r.Length))
            .Select(g => g.First() with { Project = string.Join(", ", g.Select(r => r.Project).Distinct(StringComparer.Ordinal)) })
            .OrderBy(r => r.FilePath, StringComparer.OrdinalIgnoreCase)
            .ThenBy(r => r.Line)
            .ThenBy(r => r.Column)
            .ToList();

    /// <summary>What a row says for <paramref name="count"/> references.</summary>
    public static string Text(int count) => count == 1 ? "C#: 1 reference" : $"C#: {count} references";

    /// <summary>
    /// Whether a C# file is generated code rather than code someone wrote: by the names generators
    /// give files, or an <c>&lt;auto-generated&gt;</c> comment before any code, as the compiler judges it.
    /// </summary>
    public static bool IsGenerated(string? filePath, string text)
    {
        if (filePath is not null)
        {
            var name = Path.GetFileName(filePath);
            if (GeneratedSuffixes.Any(s => name.EndsWith(s, StringComparison.OrdinalIgnoreCase)) || name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }
        foreach (var raw in (text ?? "").Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0)
            {
                continue;
            }
            if (!line.StartsWith("//", StringComparison.Ordinal) && !line.StartsWith("/*", StringComparison.Ordinal) && !line.StartsWith("*", StringComparison.Ordinal))
            {
                return false;
            }
            if (line.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0 || line.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                return true;
            }
        }
        return false;
    }
}
