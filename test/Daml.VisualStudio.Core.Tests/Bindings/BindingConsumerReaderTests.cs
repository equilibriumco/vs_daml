using System;
using System.IO;
using Daml.Build.Core.Codegen;
using Daml.VisualStudio.Core.Bindings;
using Shouldly;
using Xunit;

namespace Daml.VisualStudio.Core.Tests.Bindings;

// What a C# project generates from, as its last builds left it on disk.
public sealed class BindingConsumerReaderTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "daml-consumers-" + Guid.NewGuid().ToString("N"));

    public void Dispose()
    {
        if (Directory.Exists(_root))
        {
            Directory.Delete(_root, recursive: true);
        }
    }

    private string Project => Path.Combine(_root, "App", "App.csproj");

    // A generation of the project with one file, listed in the props of a configuration and framework.
    private void Generation(string configuration, string framework, string id, GenerationManifest manifest, string intermediate = "obj")
    {
        var folder = Path.Combine(_root, "App", "obj", configuration, framework, "Daml", "Ref-" + id);
        var file = Path.Combine(folder, "Asset.cs");
        Directory.CreateDirectory(folder);
        File.WriteAllText(file, "// <auto-generated>\n");
        (manifest with { GenerationId = id, Files = [new GenerationManifestFile("Asset.cs", "5ha")] }).Write(Path.Combine(folder, GenerationManifest.FileName));
        var list = BindingConsumerReader.ListOf(Project, configuration, framework, intermediate);
        var listed = GeneratedProps.Read(list);
        GeneratedProps.Write(list, [.. listed, new GeneratedFile(file, id)], visible: false);
    }

    [Fact, Trait("Category", "Unit")]
    public void A_custom_intermediate_directory_is_used_to_discover_consumers()
    {
        var intermediate = Path.Combine(_root, "shared-intermediate");
        Generation("Debug", "net10.0", "0123456789abcdef", GenerationProvenanceTests.Manifest(), intermediate);
        var reader = new BindingConsumerReader(new GenerationCatalog());
        reader.Read(Project, "Debug").ShouldBeEmpty();
        reader.Read(Project, "Debug", intermediate).ShouldHaveSingleItem().Project.ShouldBe(Project);
    }

    [Fact, Trait("Category", "Unit")]
    public void A_project_generates_from_the_Daml_projects_its_generations_name()
    {
        Generation("Debug", "net10.0", "0123456789abcdef", GenerationProvenanceTests.Manifest());
        Generation("Debug", "net10.0", "fedcba9876543210", GenerationProvenanceTests.Manifest() with { ReferenceKind = DamlReferenceKind.Dar, Source = null });
        Generation("Debug", "net9.0", "1111111111111111", GenerationProvenanceTests.Manifest());
        Generation("Release", "net10.0", "2222222222222222", GenerationProvenanceTests.Manifest() with { Source = new SourceProvenance(@"C:\work\Other\daml.yaml", "1") });

        var consumers = new BindingConsumerReader(new GenerationCatalog()).Read(Project, "Debug");

        consumers.ShouldBe([
            new BindingConsumer(Project, "net10.0", @"C:\work\Contracts\daml.yaml"),
            new BindingConsumer(Project, "net9.0", @"C:\work\Contracts\daml.yaml"),
        ], ignoreOrder: true);
    }

    // The name Daml.Build.CSharp gives the list: obj\daml\<project file>.<configuration>.<framework>.g.props.
    [Fact, Trait("Category", "Unit")]
    public void The_list_is_where_the_build_writes_it()
    {
        BindingConsumerReader.ListOf(@"C:\sln\App\App.csproj", "Debug", "net10.0").ShouldBe(@"C:\sln\App\obj\daml\App.csproj.Debug.net10.0.g.props");
    }

    [Fact, Trait("Category", "Unit")]
    public void A_project_never_built_generates_from_nothing_yet()
    {
        new BindingConsumerReader(new GenerationCatalog()).Read(Project, "Debug").ShouldBeEmpty();
    }
}
