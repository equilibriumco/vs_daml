using System;
using System.IO;
using Daml.Build.Core.Codegen;
using Daml.Build.Core.FileSystem;
using Daml.VisualStudio.Core.Bindings;
using Shouldly;
using Xunit;

namespace Daml.VisualStudio.Core.Tests.Bindings;

public sealed class GenerationCatalogTests : IDisposable
{
    private readonly string _root = Path.Combine(Path.GetTempPath(), "daml-catalog-" + Guid.NewGuid().ToString("N"));

    public void Dispose()
    {
        if (Directory.Exists(_root))
        {
            Directory.Delete(_root, recursive: true);
        }
    }

    private string Folder => Path.Combine(_root, @"App\obj\Debug\net10.0\Daml\Contracts-9de80d6cfe50bada");

    private string Write(string relativePath)
    {
        var path = Path.Combine(Folder, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, "// <auto-generated>\n");
        return path;
    }

    private void Publish(GenerationManifest manifest, params string[] files) =>
        (manifest with { Files = Array.ConvertAll(files, f => new GenerationManifestFile(f, "5ha")) }).Write(Path.Combine(Folder, GenerationManifest.FileName));

    [Fact, Trait("Category", "Unit")]
    public void A_file_the_manifest_lists_belongs_to_that_generation()
    {
        var point = Write(@"Fixture\Kinds\Types\Point.cs");
        Publish(GenerationProvenanceTests.Manifest(), @"Fixture\Kinds\Types\Point.cs");

        var entry = new GenerationCatalog().Find(point).ShouldNotBeNull();

        (entry.Folder, entry.RelativePath, entry.Sha256).ShouldBe((Folder, @"Fixture\Kinds\Types\Point.cs", "5ha"));
        entry.Provenance.ShouldNotBeNull().GenerationId.ShouldBe("9de80d6cfe50bada");
    }

    // The manifest's hash says whether the file is still what the generator wrote.
    [Fact, Trait("Category", "Unit")]
    public void A_file_is_unchanged_while_it_has_the_hash_the_manifest_recorded()
    {
        var point = Write(@"Fixture\Kinds\Types\Point.cs");
        (GenerationProvenanceTests.Manifest() with { Files = [new GenerationManifestFile(@"Fixture\Kinds\Types\Point.cs", Hashing.Sha256File(point))] })
            .Write(Path.Combine(Folder, GenerationManifest.FileName));
        var catalog = new GenerationCatalog();

        var before = catalog.Find(point).ShouldNotBeNull().Unchanged;
        File.AppendAllText(point, "// edited\n");
        var after = catalog.Find(point).ShouldNotBeNull().Unchanged;

        before.ShouldBeTrue();
        after.ShouldBeFalse();
    }

    // Visual Studio may hand paths in another case or with forward slashes.
    [Fact, Trait("Category", "Unit")]
    public void The_path_is_matched_as_Windows_compares_paths()
    {
        var point = Write(@"Fixture\Kinds\Types\Point.cs");
        Publish(GenerationProvenanceTests.Manifest(), @"Fixture\Kinds\Types\Point.cs");

        new GenerationCatalog().Find(point.ToUpperInvariant().Replace('\\', '/')).ShouldNotBeNull();
    }

    // A file someone put there, or one a newer generation added before its manifest: not the generator's.
    [Fact, Trait("Category", "Unit")]
    public void A_file_in_a_generation_the_manifest_doesnt_list_belongs_to_none()
    {
        var mine = Write(@"Fixture\Kinds\Types\Mine.cs");
        Publish(GenerationProvenanceTests.Manifest(), @"Fixture\Kinds\Types\Point.cs");

        new GenerationCatalog().Find(mine).ShouldBeNull();
    }

    [Fact, Trait("Category", "Unit")]
    public void A_file_outside_any_generation_belongs_to_none()
    {
        var program = Path.Combine(_root, @"App\Program.cs");
        Directory.CreateDirectory(Path.GetDirectoryName(program)!);
        File.WriteAllText(program, "");

        new GenerationCatalog().Find(program).ShouldBeNull();
        new GenerationCatalog().Find(@"Z:\nowhere\Program.cs").ShouldBeNull();
    }

    [Fact, Trait("Category", "Unit")]
    public void A_generation_whose_manifest_doesnt_record_its_package_has_no_provenance()
    {
        var point = Write(@"Fixture\Kinds\Types\Point.cs");
        Publish(GenerationProvenanceTests.Manifest(withPackage: false), @"Fixture\Kinds\Types\Point.cs");

        new GenerationCatalog().Find(point).ShouldNotBeNull().Provenance.ShouldBeNull();
    }

    // Manifests are read once; a republished generation is read again once it is forgotten.
    [Fact, Trait("Category", "Unit")]
    public void A_forgotten_generation_is_read_again()
    {
        var point = Write(@"Fixture\Kinds\Types\Point.cs");
        Publish(GenerationProvenanceTests.Manifest(), @"Fixture\Kinds\Types\Point.cs");
        var catalog = new GenerationCatalog();
        catalog.Find(point).ShouldNotBeNull();
        Publish(GenerationProvenanceTests.Manifest(), @"Fixture\Kinds\Types\Other.cs");

        var cached = catalog.Find(point);
        catalog.Forget(Folder);
        var reread = catalog.Find(point);

        cached.ShouldNotBeNull();
        reread.ShouldBeNull();
    }
}
