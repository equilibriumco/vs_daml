using Equilibrium.Daml.VisualStudio.Core.Bindings;
using Shouldly;
using Xunit;

namespace Equilibrium.Daml.VisualStudio.Core.Tests.Bindings;

// What a row says and the window lists of the C# that uses a Daml declaration.
public class CSharpReferencesTests
{
    private static CSharpReference At(string project, string file, int line, int start, string code = "new Asset(alice, bob, \"Gold\")") =>
        new(project, file, line, 5, start, 5, code);

    // A file in two target frameworks of a project, or linked into two projects, is one place in the source.
    [Fact, Trait("Category", "Unit")]
    public void One_place_counts_once_whatever_compiles_it()
    {
        var summary = CSharpReferences.Summarize([
            At("App (net10.0)", @"C:\sln\App\Program.cs", 4, 120),
            At("App (net9.0)", @"C:\sln\App\Program.cs", 4, 120),
            At("Web", @"C:\sln\Shared\Use.cs", 9, 40),
            At("App (net10.0)", @"c:\sln\shared\use.cs", 9, 40),
            At("App (net10.0)", @"C:\sln\App\Program.cs", 2, 30),
        ]);

        summary.ShouldBe([
            At("App (net10.0)", @"C:\sln\App\Program.cs", 2, 30),
            At("App (net10.0), App (net9.0)", @"C:\sln\App\Program.cs", 4, 120),
            At("Web, App (net10.0)", @"C:\sln\Shared\Use.cs", 9, 40),
        ]);
    }

    [Theory, Trait("Category", "Unit")]
    [InlineData(0, "C#: 0 references")]
    [InlineData(1, "C#: 1 reference")]
    [InlineData(12, "C#: 12 references")]
    public void A_row_says_how_many_references_there_are(int count, string text)
    {
        CSharpReferences.Text(count).ShouldBe(text);
    }

    // Generated code, the bindings themselves among it, isn't a use anyone wrote.
    [Theory, Trait("Category", "Unit")]
    [InlineData(@"C:\sln\App\Program.cs", "using Daml.Runtime.Data;\nvar x = 1;", false)]
    [InlineData(@"C:\sln\App\obj\Debug\net10.0\Daml\Ref-1\Asset.cs", "// <auto-generated>\n// This code was generated.\n// </auto-generated>\n", true)]
    [InlineData(@"C:\sln\App\Resources.Designer.cs", "namespace App;", true)]
    [InlineData(@"C:\sln\App\obj\Debug\net10.0\App.AssemblyInfo.g.cs", "", true)]
    [InlineData(@"C:\sln\App\Model.cs", "/* <autogenerated /> */\nclass M {}", true)]
    [InlineData(@"C:\sln\App\Late.cs", "class Late {}\n// <auto-generated> only mentioned later\n", false)]
    public void Generated_files_are_told_by_their_name_or_leading_comment(string path, string text, bool generated)
    {
        CSharpReferences.IsGenerated(path, text).ShouldBe(generated);
    }
}
