using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Shouldly;
using Xunit;

namespace Daml.TestHelpers.Tests;

public class FakeDpmTests
{
    [Fact, Trait("Category", "Process")]
    public async Task Answers_a_scripted_command()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands = { new FakeDpmCommand { Args = { "--version" }, Stdout = "version: 1.0.22\n" } },
        });

        var result = await dpm.RunAsync(Path.GetTempPath(), "--version");

        result.ExitCode.ShouldBe(0);
        result.Stdout.ShouldBe("version: 1.0.22\n");
    }

    [Fact, Trait("Category", "Process")]
    public async Task Passes_through_exit_code_and_stderr()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands = { new FakeDpmCommand { Args = { "build" }, Stderr = "ERROR: Creation of DAR file failed.\n", ExitCode = 1 } },
        });

        var result = await dpm.RunAsync(Path.GetTempPath(), "build");

        result.ExitCode.ShouldBe(1);
        result.Stderr.ShouldBe("ERROR: Creation of DAR file failed.\n");
    }

    [Fact, Trait("Category", "Process")]
    public async Task Unscripted_command_fails_loudly()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario());

        var result = await dpm.RunAsync(Path.GetTempPath(), "install", "9.9.9");

        result.ExitCode.ShouldBe(FakeDpm.UnscriptedExitCode);
        result.Stderr.ShouldContain("install 9.9.9");
    }

    [Fact, Trait("Category", "Process")]
    public async Task Wildcard_matches_any_single_argument_and_writes_files_relative_to_cwd()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands =
            {
                new FakeDpmCommand
                {
                    Args = { "codegen-cs", "--dar", "*", "--out", "gen" },
                    WriteFiles = { ["gen/Asset.cs"] = "// <auto-generated>\n" },
                },
            },
        });
        var cwd = Directory.CreateDirectory(Path.Combine(dpm.RootDirectory, "work")).FullName;

        var result = await dpm.RunAsync(cwd, "codegen-cs", "--dar", @"C:\any\path\x.dar", "--out", "gen");

        result.ExitCode.ShouldBe(0);
        File.ReadAllText(Path.Combine(cwd, "gen", "Asset.cs")).ShouldBe("// <auto-generated>\n");
    }

    // The generator writes where --out says, wherever it runs from.
    [Fact, Trait("Category", "Process")]
    public async Task Files_under_the_out_token_go_where_out_points()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands =
            {
                new FakeDpmCommand
                {
                    Args = { "codegen-cs", "--dar", "*", "--out", "*" },
                    WriteFiles = { ["{out}/MiniDemo/Asset.cs"] = "// <auto-generated>\n" },
                },
            },
        });
        var cwd = Directory.CreateDirectory(Path.Combine(dpm.RootDirectory, "work")).FullName;
        var output = Path.Combine(dpm.RootDirectory, "elsewhere", "staging");

        var result = await dpm.RunAsync(cwd, "codegen-cs", "--dar", @"C:\any\path\x.dar", "--out", output);

        result.ExitCode.ShouldBe(0);
        File.ReadAllText(Path.Combine(output, "MiniDemo", "Asset.cs")).ShouldBe("// <auto-generated>\n");
    }

    // A build writes a DAR, which is a zip and no text.
    [Fact, Trait("Category", "Process")]
    public async Task Base64_content_is_written_as_its_bytes()
    {
        byte[] bytes = [0x50, 0x4B, 0x03, 0x04, 0x00, 0xFF, 0x0A];
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands =
            {
                new FakeDpmCommand
                {
                    Args = { "build" },
                    WriteFiles = { [@".daml\dist\contracts-1.2.0.dar"] = "base64:" + Convert.ToBase64String(bytes) },
                },
            },
        });
        var cwd = Directory.CreateDirectory(Path.Combine(dpm.RootDirectory, "pkg")).FullName;

        var result = await dpm.RunAsync(cwd, "build");

        result.ExitCode.ShouldBe(0);
        File.ReadAllBytes(Path.Combine(cwd, @".daml\dist\contracts-1.2.0.dar")).ShouldBe(bytes);
    }

    [Fact, Trait("Category", "Process")]
    public async Task Records_every_call_with_arguments_cwd_and_dpm_environment()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands = { new FakeDpmCommand { Args = { "versions", "-o", "json" }, Stdout = "[]" } },
        });
        var cwd = Directory.CreateDirectory(Path.Combine(dpm.RootDirectory, "pkg")).FullName;

        await dpm.RunAsync(cwd, new Dictionary<string, string> { ["DPM_AUTO_INSTALL"] = "true", ["UNRELATED"] = "x" }, "versions", "-o", "json");
        await dpm.RunAsync(cwd, "unknown");

        var calls = dpm.ReadCalls();
        calls.Count.ShouldBe(2);
        calls[0].Args.ShouldBe(new[] { "versions", "-o", "json" });
        calls[0].WorkingDirectory.ShouldBe(cwd);
        calls[0].Environment["DPM_AUTO_INSTALL"].ShouldBe("true");
        calls[0].Environment.Keys.ShouldNotContain("UNRELATED");
        calls[1].Args.Single().ShouldBe("unknown");
    }

    // Builds run in parallel start several dpms at once; each of them has to get its line in.
    [Fact, Trait("Category", "Process")]
    public async Task Calls_made_at_once_are_all_recorded()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario
        {
            Commands = { new FakeDpmCommand { Args = { "--version" }, Stdout = "version: 1.0.22\n" } },
        });

        var results = await Task.WhenAll(Enumerable.Range(0, 24).Select(_ => dpm.RunAsync(Path.GetTempPath(), "--version")));

        results.ShouldAllBe(r => r.ExitCode == 0, string.Join("\n", results.Select(r => r.Stderr)));
        dpm.ReadCalls().Count.ShouldBe(24);
    }

    [Theory, Trait("Category", "Process")]
    [InlineData("plain")]
    [InlineData("with space")]
    [InlineData("")]
    [InlineData("quote\"inside")]
    [InlineData(@"C:\Program Files\x\")]
    [InlineData(@"trailing\\")]
    [InlineData("zażółć & %PATH% !x!")]
    public async Task Arguments_reach_the_process_unchanged(string awkward)
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario());

        await dpm.RunAsync(dpm.RootDirectory, "echo", awkward, "end");

        dpm.ReadCalls().Single().Args.ShouldBe(new[] { "echo", awkward, "end" });
    }

    [Fact, Trait("Category", "Process")]
    public void Exposes_itself_as_dpm_exe_in_its_own_bin_directory()
    {
        using var dpm = FakeDpm.Create(new FakeDpmScenario());

        Path.GetFileName(dpm.ExecutablePath).ShouldBe("dpm.exe");
        Path.GetDirectoryName(dpm.ExecutablePath).ShouldBe(dpm.BinDirectory);
        File.Exists(dpm.ExecutablePath).ShouldBeTrue();
    }
}
